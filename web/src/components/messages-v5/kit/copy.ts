/**
 * Messages v5 kit copy. Every user-facing string the kit renders comes through
 * the dashboard i18n catalogue (`web/messages/{en,es,fr}.json`) under
 * `dashboard.messagesV5.*`; refusals reuse `dashboard.pos.messages.refusal.*`.
 *
 * Components take a `KitCopy` (or a slice of it) as a prop so they stay pure
 * and server-renderable; `useKitCopy()` in `use-kit-copy.ts` builds one from
 * the dashboard translator on the client. Keys are written as literals on
 * purpose: `src/i18n/message-key-usage.static.test.ts` reads them to prove
 * every catalogue key has a reader.
 *
 * House rules baked in: no em dashes, "client" never "customer", USD.
 */

