/** `{name}` substitution; unknown holes stay visible so a missing param is seen, not hidden. */
export function fill(template: string, params: Record<string, string | number>): string {
  return template.replace(/\{(\w+)\}/g, (hole, key: string) => (key in params ? String(params[key]) : hole));
}

