export type PromoCopy = {
  locale: "es" | "en";
  t: (key: PromoCopyKey, vars?: Readonly<Record<string, string | number>>) => string;
};

/** ES for Spanish locales; every other locale reads EN. */
export function promoCopy(locale: string | null | undefined): PromoCopy {
  const lang: "es" | "en" = (locale ?? "").toLowerCase().startsWith("es") ? "es" : "en";
  const dict: Readonly<Record<PromoCopyKey, string>> = lang === "es" ? PROMO_COPY_ES : PROMO_COPY_EN;
  return {
    locale: lang,
    t(key, vars) {
      const raw = dict[key];
      if (!vars) return raw;
      return raw.replace(/\{(\w+)\}/g, (m, name: string) => (name in vars ? String(vars[name]) : m));
    },
  };
}
