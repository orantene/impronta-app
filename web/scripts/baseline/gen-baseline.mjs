#!/usr/bin/env node
// Prototype baseline-schema generator (option B, card 272).
//
// Input : a JSON catalog snapshot (produced by catalog-snapshot.sql). NO live connection.
// Output: SQL in dependency order. COVERS ONLY: extensions, enums, tables + columns
//         (type, NOT NULL, default, identity, stored generated), PRIMARY KEY / UNIQUE /
//         FOREIGN KEY constraints, and non-constraint indexes.
// NOT covered: functions, triggers, RLS + policies, views, matviews, sequences ownership,
//         grants, comments, storage buckets, auth/storage objects. A column default that
//         calls a function, or an index using a custom operator class, fails on replay
//         until those objects exist.
//
// Usage: node scripts/baseline/gen-baseline.mjs <snapshot.json> [out.sql]

import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const q = (ident) => `"${String(ident).replace(/"/g, '""')}"`;
const lit = (s) => `'${String(s).replace(/'/g, "''")}'`;

/** Target table of a pg_get_constraintdef FOREIGN KEY, e.g. "public.x" or "auth.users" -> {schema,name}. */
export function fkTarget(def) {
  const m = /REFERENCES\s+((?:"[^"]+"|[\w$]+)(?:\.(?:"[^"]+"|[\w$]+))?)\s*\(/i.exec(def);
  if (!m) return null;
  const parts = m[1].split(".").map((p) => p.replace(/^"|"$/g, ""));
  return parts.length === 2 ? { schema: parts[0], name: parts[1] } : { schema: "public", name: parts[0] };
}

/** Kahn topological order of tables by FK edges; ties by name; cycle members appended by name. */
export function orderTables(tables) {
  const names = new Set(tables.map((t) => t.name));
  const deps = new Map();
  for (const t of tables) {
    const d = new Set();
    for (const c of t.constraints ?? []) {
      if (c.type !== "f") continue;
      const tg = fkTarget(c.def);
      if (tg && tg.schema === "public" && tg.name !== t.name && names.has(tg.name)) d.add(tg.name);
    }
    deps.set(t.name, d);
  }
  const out = [];
  const done = new Set();
  let pending = [...names].sort();
  while (pending.length) {
    const ready = pending.filter((n) => [...deps.get(n)].every((x) => done.has(x)));
    if (!ready.length) {
      out.push(...pending);
      break;
    }
    for (const n of ready) {
      out.push(n);
      done.add(n);
    }
    pending = pending.filter((n) => !done.has(n));
  }
  const byName = new Map(tables.map((t) => [t.name, t]));
  return out.map((n) => byName.get(n));
}

function columnSql(c) {
  let s = `  ${q(c.name)} ${c.type}`;
  if (c.generated) s += ` GENERATED ALWAYS AS (${c.generated}) STORED`;
  else if (c.identity === "a") s += " GENERATED ALWAYS AS IDENTITY";
  else if (c.identity === "d") s += " GENERATED BY DEFAULT AS IDENTITY";
  else if (c.default != null) s += ` DEFAULT ${c.default}`;
  if (c.notNull) s += " NOT NULL";
  return s;
}

/** Returns { sql, warnings }. */
export function generateBaseline(snapshot) {
  const warnings = [];
  const out = [];
  const tables = orderTables(snapshot.tables ?? []);
  const known = new Set(tables.map((t) => t.name));

  out.push("-- GENERATED by web/scripts/baseline/gen-baseline.mjs. Do not edit by hand.");
  out.push("-- Covers: extensions, enums, tables/columns, PK/UNIQUE/FK, indexes. Nothing else.");
  out.push("set search_path = public, extensions;\n");

  for (const e of snapshot.extensions ?? []) {
    out.push(`create extension if not exists ${q(e.name)} with schema ${q(e.schema)};`);
  }
  for (const e of snapshot.enums ?? []) {
    out.push(`create type public.${q(e.name)} as enum (${e.labels.map(lit).join(", ")});`);
  }
  out.push("");
  for (const t of tables) {
    out.push(`create table public.${q(t.name)} (\n${t.columns.map(columnSql).join(",\n")}\n);`);
  }
  out.push("");
  // PK + UNIQUE before FKs (FKs need a unique target); indexes next; FKs last so
  // table order never matters for referential constraints (including cycles).
  for (const kind of ["p", "u"]) {
    for (const t of tables)
      for (const c of t.constraints ?? [])
        if (c.type === kind)
          out.push(`alter table public.${q(t.name)} add constraint ${q(c.name)} ${c.def};`);
  }
  for (const t of tables) for (const i of t.indexes ?? []) out.push(`${i.def};`);
  for (const t of tables) {
    for (const c of t.constraints ?? []) {
      if (c.type !== "f") continue;
      const tg = fkTarget(c.def);
      const missing = tg && tg.schema === "public" && !known.has(tg.name);
      if (missing) {
        warnings.push(`${t.name}.${c.name}: references public.${tg.name}, not in snapshot; skipped`);
        out.push(`-- SKIPPED ${c.name} (target public.${tg.name} not in snapshot)`);
        continue;
      }
      out.push(`alter table public.${q(t.name)} add constraint ${q(c.name)} ${c.def};`);
    }
  }
  return { sql: out.join("\n") + "\n", warnings };
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const [, , inFile, outFile] = process.argv;
  if (!inFile) {
    console.error("usage: gen-baseline.mjs <snapshot.json> [out.sql]");
    process.exit(2);
  }
  const raw = JSON.parse(readFileSync(inFile, "utf8"));
  const snap = Array.isArray(raw) ? raw[0].snapshot : (raw.snapshot ?? raw);
  const { sql, warnings } = generateBaseline(snap);
  if (outFile) writeFileSync(outFile, sql);
  else process.stdout.write(sql);
  for (const w of warnings) console.error(`warn: ${w}`);
}
